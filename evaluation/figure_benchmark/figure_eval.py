"""Phase 0 figure benchmark on the synthetic corpus: detection / linking, then retrieval with and without figures.

    python -m evaluation.figure_benchmark.figure_eval [--out evaluation/results/figure_eval.json]

Detection (per figure of the ground truth)
    found      a kept figure with the right label on the right page
    kind       raster / vector classified correctly
    caption    the stored caption equals the generated one
    mentioned  at least one citing sentence is linked
    false+     kept figures that are not in the ground truth (logos, banners, icons that slipped through)

Retrieval (36 questions over 6 papers in one index, vector search only)
    baseline   figures disabled: captions are ordinary paragraphs, chart images are OCR chunks
    phase0     figures enabled: one figure chunk per chart (caption + text in figure + citing sentence)
    A hit is correct when it comes from the right paper and its text contains the figure's caption.

The corpus is generated by the same team that wrote the detector (see synthetic.py): read the numbers as a check
that the mechanism works, not as an estimate of real-world accuracy.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import shutil
import tempfile
from pathlib import Path

from ai.chunking import EMBEDDING_MODEL, ChunkContext, ChunkingEngine, IndexingService, default_token_counter
from ai.embedding import BgeEmbedder
from ai.ingestion.ingestion_pipeline import IngestionPipeline
from ai.retrieval import RetrievalService
from ai.storage import SQLiteParentStore
from ai.vectorstore import ChromaVectorStore
from evaluation.figure_benchmark.synthetic import build

USER = COURSE = "fig"


def detection(corpus: Path, truth: dict) -> dict:
    pipeline = IngestionPipeline()
    total = found = kind_ok = caption_ok = mentioned = false_pos = 0
    negatives = negatives_rejected = 0
    rows = []
    for paper in truth["papers"]:
        document = pipeline.ingest(corpus / paper["file"])
        kept = [f for page in document.pages for f in page.figures]
        wanted = {(f["page"], f["label"]): f for f in paper["figures"]}
        for key, expected in wanted.items():
            total += 1
            match = next((f for f in kept if (f.page_number, f.label) == key), None)
            if match is None:
                rows.append({"file": paper["file"], "figure": key, "problem": "not found"})
                continue
            found += 1
            kind_ok += (match.kind == "raster") == (expected["embed"] == "raster")
            caption_ok += match.caption == expected["caption"]
            mentioned += bool(match.mentions)
        false_pos += sum(1 for f in kept if (f.page_number, f.label) not in wanted)
        decisions = document.metadata.get("figures", {}).get("decisions", [])
        negatives += len(paper["negatives"])
        negatives_rejected += sum(1 for d in decisions if not d["keep"])
    return {
        "figures": total, "found": found, "found_rate": round(found / total, 3),
        "kind_correct": kind_ok, "caption_exact": caption_ok, "citing_sentence_linked": mentioned,
        "false_positives": false_pos, "negatives": negatives, "negatives_rejected_by_selection": negatives_rejected,
        "problems": rows,
    }


def build_index(corpus: Path, truth: dict, workdir: Path, figures: bool):
    store = ChromaVectorStore(path=workdir / "chroma")
    parents = SQLiteParentStore(workdir / "parents.sqlite3")
    embedder = BgeEmbedder()
    indexer = IndexingService(embedder, store, parent_store=parents)
    engine = ChunkingEngine(tokenizer=default_token_counter(), strict=False)
    pipeline = IngestionPipeline(enable_figures=figures)
    kinds: dict[str, int] = {}
    for paper in truth["papers"]:
        document = pipeline.ingest(corpus / paper["file"])
        uid = "doc-" + paper["file"]
        chunks = engine.run(document, ChunkContext(USER, COURSE, uid, EMBEDDING_MODEL))
        indexer.index(chunks.children, document_uid=uid, parents=chunks.parents)
        for c in chunks.children:
            kinds[c.kind] = kinds.get(c.kind, 0) + 1
    return RetrievalService(embedder, store, parent_store=parents), kinds


def retrieval(service: RetrievalService, truth: dict) -> dict:
    ranks = []
    for q in truth["questions"]:
        result = service.search(q["q"], user_id=USER, course_id=COURSE, k=5, rerank=False, assess_relevance=False)
        needle = q["caption"][:40]
        rank = next(
            (i + 1 for i, h in enumerate(result.hits) if h.file_name == q["file"] and needle in h.text.replace("\n", " ")), None
        )
        ranks.append(rank)
    n = len(ranks)
    return {
        "questions": n,
        "hit@1": round(sum(r == 1 for r in ranks) / n, 3),
        "hit@3": round(sum(r is not None and r <= 3 for r in ranks) / n, 3),
        "hit@5": round(sum(r is not None for r in ranks) / n, 3),
        "mrr@5": round(sum(1 / r for r in ranks if r) / n, 3),
    }


def main() -> None:
    os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
    logging.disable(logging.CRITICAL)
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path("evaluation/results/figure_eval.json"))
    args = parser.parse_args()
    workdir = Path(tempfile.mkdtemp(prefix="figure_eval_"))
    try:
        corpus = workdir / "corpus"
        truth = build(corpus)
        report = {"detection": detection(corpus, truth)}
        for name, figures in (("baseline", False), ("phase0", True)):
            service, kinds = build_index(corpus, truth, workdir / name, figures)
            report[name] = {**retrieval(service, truth), "chunk_kinds": kinds}
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(report, indent=1), encoding="utf-8")
        print(json.dumps(report, indent=1))
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    main()
